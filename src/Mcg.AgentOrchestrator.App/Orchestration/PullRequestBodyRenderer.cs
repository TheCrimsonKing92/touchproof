using System.Text.RegularExpressions;
using Mcg.AgentOrchestrator.Core;
using Mcg.AgentOrchestrator.Infrastructure;

namespace Mcg.AgentOrchestrator.App.Orchestration;

internal static class PullRequestBodyRenderer
{
    // Redact machine-local paths while preserving repository-relative paths.
    private static readonly Regex LocalPath = new(
        """(?:file:[^\s`"<>]+|(?<!\w)[A-Za-z]:[\\/][^\r\n`"<>]*|\\\\[^\s`"<>]+|(?<![\w./\\])~[\\/][^\s`"<>]+|(?<![\w./\\])[\\/](?:[A-Za-z][\\/])?(?i:users|home|documents and settings)[\\/][^\s`"<>]+)""",
        RegexOptions.CultureInvariant);
    private static readonly Regex UserDirectory = new(
        "(?i)[\\\\/](?:users|home|documents and settings)[\\\\/]([^\\\\/\\s`\"<>]+)", RegexOptions.CultureInvariant);

    public static (string Title, string Body) Render(Goal goal, string attemptId, IReadOnlyList<string> checkNames,
        params string[] redactionSources)
    {
        // Attempt identities are generated by the gate, not arbitrary receipt text.
        if (!Regex.IsMatch(attemptId, @"\A[A-Za-z0-9-]{1,128}\z"))
            throw new InvalidOperationException("Unsafe gate attempt identity.");
        var criteria = goal.RefinedSpec?.AcceptanceCriteria ?? AcceptanceCriteriaParser.ParseDeclared(goal.Objective);
        var summary = goal.Objective.Split(['\r', '\n'], StringSplitOptions.RemoveEmptyEntries).First().Trim().TrimStart('#').Trim();
        var headingMatch = Regex.Match(goal.Objective, @"(?m)^\s*#+\s+(.+)$");
        var heading = headingMatch.Success ? headingMatch.Groups[1].Value.Trim() : summary;
        var approved = new[] { summary, heading }.Concat(criteria).Concat(checkNames).ToArray();
        // Sources supply only redaction identities; their content is never included in the body.
        var usernames = approved.Concat(redactionSources).Append(goal.Objective)
            .SelectMany(source => UserDirectory.Matches(source.Replace("\\\\", "\\", StringComparison.Ordinal)).Cast<Match>())
            .Select(match => match.Groups[1].Value.TrimEnd('.', ',', ')', ']', '}'))
            .Where(value => value.Length > 0).Distinct(StringComparer.OrdinalIgnoreCase).ToArray();
        string Scrub(string value)
        {
            value = LocalPath.Replace(value, "[redacted]");
            value = Regex.Replace(value, @"(?i)\S*\.orchestrator\S*", "[redacted]");
            foreach (var username in usernames)
                value = Regex.Replace(value, Regex.Escape(username), "[redacted]", RegexOptions.IgnoreCase | RegexOptions.CultureInvariant);
            value = ForgeDiagnosticRedactor.Redact(value);
            return value.Replace('\r', ' ').Replace('\n', ' ').Trim();
        }
        var title = Scrub(summary);
        var lines = new List<string> { title };
        var safeHeading = Scrub(heading);
        if (safeHeading != title) lines.Add(safeHeading);
        lines.Add("");
        var changeSummary = RenderChangeSummary(goal.Objective, Scrub);
        if (changeSummary is not null)
        {
            lines.Add("## What this changes");
            if (changeSummary.Length > 0)
            {
                lines.Add("");
                lines.Add(changeSummary);
            }
            lines.Add("");
        }
        lines.Add("## Acceptance criteria");
        lines.Add("");
        lines.AddRange(criteria.Select((criterion, index) => $"{index + 1}. {Scrub(criterion)}"));
        lines.Add("");
        lines.Add("## Gate");
        lines.Add("");
        lines.Add($"acceptance gate passed, attempt {attemptId}, checks: {string.Join(", ", checkNames.Select(Scrub))}");
        var body = string.Join(Environment.NewLine, lines);
        ValidateContent(title, body, usernames);
        return (title, body);
    }

    private static string? RenderChangeSummary(string objective, Func<string, string> scrub)
    {
        const int characterLimit = 3000;
        var sourceLines = objective.Split('\n').Select(line => line.TrimEnd('\r')).ToArray();
        var headingIndex = Array.FindIndex(sourceLines,
            line => line.StartsWith("## What to build", StringComparison.Ordinal));
        if (headingIndex < 0) return null;

        var summaryLines = sourceLines.Skip(headingIndex + 1)
            .TakeWhile(line => !line.StartsWith("## ", StringComparison.Ordinal))
            .Select(line =>
            {
                // Scrub trims whitespace; restore indentation so nested lists retain their structure.
                var indentLength = line.Length - line.TrimStart().Length;
                var safeLine = scrub(line);
                return safeLine.Length == 0 ? "" : line[..indentLength] + safeLine;
            }).ToArray();
        var summary = string.Join(Environment.NewLine, summaryLines);
        if (summary.Length <= characterLimit) return summary;

        var retainedLines = new List<string>();
        var retainedLength = 0;
        foreach (var line in summaryLines)
        {
            // Reserve the separator and final ellipsis line before retaining each complete line.
            var addedLength = line.Length + Environment.NewLine.Length;
            if (retainedLength + addedLength + 1 > characterLimit) break;
            retainedLines.Add(line);
            retainedLength += addedLength;
        }
        retainedLines.Add("…");
        return string.Join(Environment.NewLine, retainedLines);
    }

    internal static void ValidateContent(string title, string body, IReadOnlyList<string> usernames)
    {
        if (string.IsNullOrWhiteSpace(title) || LocalPath.IsMatch(body) ||
            body.Contains(".orchestrator", StringComparison.OrdinalIgnoreCase) ||
            usernames.Any(name => body.Contains(name, StringComparison.OrdinalIgnoreCase)))
            throw new InvalidOperationException("Pull request content could not be rendered safely.");
    }
}
