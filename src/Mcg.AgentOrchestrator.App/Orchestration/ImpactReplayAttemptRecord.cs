namespace Mcg.AgentOrchestrator.App.Orchestration;

// One historical candidate and its counterfactual lane selection; never a gate verdict.
internal sealed record ImpactReplayAttemptRecord(
    string AttemptId,
    string GoalId,
    DateTimeOffset StartedAt,
    string MainHeadSha,
    string BranchHeadSha,
    string SelectionOutcome,
    string? DegradationKind,
    string? SelectionReason,
    IReadOnlyList<string> ChangedFiles,
    IReadOnlyList<string> SelectedTestClasses,
    IReadOnlyList<string> FloorLanes,
    IReadOnlyList<string> RanLanes,
    IReadOnlyList<string> WouldRunLanes,
    IReadOnlyList<string> SkippedLanes,
    double EstimatedSerialSecondsSaved,
    IReadOnlyList<ImpactReplayLaneOutcome> LaneOutcomes,
    IReadOnlyList<ImpactReplayFailingClass> FailingClasses,
    bool MissCheckComplete,
    IReadOnlyList<string> EvidenceWarnings,
    int ChangedSourceFileCount = 0,
    IReadOnlyList<ImpactReplayBalancedClass>? BalancedClasses = null,
    IReadOnlyList<ImpactReplayLaneOutcome>? BalancedLaneOutcomes = null,
    double PoolSecondsSaved = 0,
    double NamedLaneObservedSecondsSaved = 0,
    double ObservedInfrastructureSeconds = 0,
    bool DurationCoverageComplete = true,
    IReadOnlyList<ImpactReplayUnresolvedFailure>? UnresolvedFailures = null,
    IReadOnlyList<string>? OutOfInfrastructureTestFiles = null,
    double? ClassLevelSecondsSaved = null,
    double? ClassLevelNonFloorTestSeconds = null,
    string? ClassLevelUnavailableReason = null,
    double? ClassLevelCpuSecondsSaved = null,
    string? ClassLevelCpuUnavailableReason = null,
    ImpactReplayDeclaredGuardReport? DeclaredGuards = null,
    int? UnboundedSelectedClassCount = null,
    double? UnboundedNonFloorTestSecondsShare = null,
    string? UnboundedClassCountUnavailableReason = null,
    string? UnboundedDurationShareUnavailableReason = null)
{
    public double ShareOfLanesSkipped => RanLanes.Count == 0 ? 0 : (double)SkippedLanes.Count / RanLanes.Count;
}
